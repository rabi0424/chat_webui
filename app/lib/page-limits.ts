/**
 * 取り込んだページの長さの上限。
 *
 * 本文を作る側（`page-extract.client.ts`）と、切ったことを画面に出す側
 * （Composer）が同じ値を見る。入力欄は `.client` のモジュールを静的には
 * 読まない（取り込みは貼られたときに初めて読み込む）ので、値だけを
 * ここに置く——書き写すと、上限を変えたときに画面の断りだけが古くなる。
 */

/**
 * モデルへ渡す本文の上限（文字数）。
 *
 * 日本語で4万字はおよそ3万トークン。記事1本としては十分に長く、
 * 128kのコンテキストでも会話の続きが入る余地が残る。超えたぶんは
 * 落として、落としたことを本文の末尾と札の両方に出す（黙って切ると、
 * モデルは「そこで終わっている文書」として読む）。
 */
export const MAX_PAGE_TEXT_CHARS = 40_000;

/** 切ったことを本文に書く印。 */
export const TRUNCATED_MARK = "…（長すぎるため、ここで切りました）";
